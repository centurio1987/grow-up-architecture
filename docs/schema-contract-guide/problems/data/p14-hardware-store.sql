-- 외래 키 선언은 원래 DB에도 없습니다.
CREATE TABLE TB_ITEM (
  ITEM_CD  CHAR(8) PRIMARY KEY,
  ITEM_NM  VARCHAR(60),
  CAT1     CHAR(2),
  CAT2     CHAR(2),
  UNIT     VARCHAR(10),
  PRICE1   INTEGER,
  PRICE2   INTEGER,
  PRICE3   INTEGER,
  CUST_CD  CHAR(5),
  MEMO     VARCHAR(200),
  USE_YN   CHAR(1)
);
CREATE TABLE TB_STOCK (
  ITEM_CD  CHAR(8),
  WH_CD    CHAR(2),
  QTY      INTEGER,
  UPD_DT   CHAR(8)
);
CREATE TABLE TB_INOUT (
  SEQ      INTEGER PRIMARY KEY,
  DT       CHAR(8),
  ITEM_CD  CHAR(8),
  IO_GB    CHAR(1),
  QTY      INTEGER,
  WH_CD    CHAR(2),
  CUST_CD  CHAR(5),
  REMARK   VARCHAR(100)
);
CREATE TABLE TB_CUST (
  CUST_CD  CHAR(5) PRIMARY KEY,
  CUST_NM  VARCHAR(60),
  TEL      VARCHAR(20),
  CUST_GB  CHAR(1)
);
CREATE TABLE TB_CODE (
  GRP_CD   VARCHAR(10),
  CD       VARCHAR(10),
  CD_NM    VARCHAR(40),
  SORT     INTEGER
);

